# =========================================================================== schemas
async def _listing(naming: str) -> dict[str, Any]:
    ctx = make_test_context({"tools.profile": "full", "tools.enable": ["computer"]})
    async with Client(build_server(ctx, naming=naming)) as client:
        tools = (await client.list_tools()).tools
    return {tool.name: tool for tool in tools}


def _resolve(schema: dict[str, Any], defs: dict[str, Any]) -> dict[str, Any]:
    ref = schema.get("$ref")
    if isinstance(ref, str) and ref.startswith("#/$defs/"):
        return defs.get(ref.removeprefix("#/$defs/"), {})
    return schema


def _type(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    schema = _resolve(schema, defs)
    if "enum" in schema:
        return " | ".join(f"`{value}`" if isinstance(value, str) else str(value) for value in schema["enum"])
    if "const" in schema:
        return f"`{schema['const']}`"
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = [_type(option, defs) for option in schema[key] if option.get("type") != "null"]
            nullable = any(option.get("type") == "null" for option in schema[key])
            text = " | ".join(dict.fromkeys(parts))
            return f"{text} (optional)" if nullable and text else text
    kind = schema.get("type")
    if kind == "array":
        return f"list of {_type(schema.get('items', {}), defs)}"
    if kind == "object" or "properties" in schema:
        title = schema.get("title")
        return f"object ({title})" if title else "object"
    if isinstance(kind, list):
        return " | ".join(str(k) for k in kind if k != "null")
    return str(kind or "any")


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _default(schema: dict[str, Any], required: bool) -> str:
    if required:
        return "required"
    if "default" not in schema:
        return "optional"
    value = schema["default"]
    if value is None:
        return "optional"
    return f"`{json.dumps(value, ensure_ascii=False)}`"


def _parameters(input_schema: dict[str, Any]) -> list[str]:
    properties: dict[str, Any] = input_schema.get("properties", {})
    if not properties:
        return ["No parameters."]
    defs = input_schema.get("$defs", {})
    required = set(input_schema.get("required", []))
    rows = ["| Parameter | Type | Default | Description |", "|---|---|---|---|"]
    for name, schema in properties.items():
        description = schema.get("description") or _resolve(schema, defs).get("description", "")
        rows.append(
            f"| `{name}` | {_cell(_type(schema, defs))} | {_default(schema, name in required)} | {_cell(description)} |"
        )
    return rows


def _returns(output_schema: dict[str, Any] | None) -> str:
    if not output_schema:
        return ""
    names = [name for name in output_schema.get("properties", {}) if name != "warnings"]
    fields = ", ".join(f"`{name}`" for name in names)
    return f"**Returns** (structured content): {fields}, and `warnings`." if fields else ""


def _badges(spec: ToolSpec) -> str:
    badges: list[str] = []
    if spec.read_only:
        badges.append("read-only")
    if spec.destructive:
        badges.append("destructive")
    if spec.idempotent:
        badges.append("idempotent")
    if spec.open_world:
        badges.append("open world")
    if spec.input_action:
        badges.append("input")
    if spec.destructive or spec.name in {"shell", "applescript", "browser_eval_js"}:
        badges.append("asks first" if spec.confirm_when is None else "asks first (some actions)")
    return " · ".join(badges)


def _profiles(name: str) -> str:
    found = [profile for profile in PROFILES if name in PROFILES[profile]]
    return ", ".join(f"`{p}`" for p in found) if found else "none (enable it with `[tools] enable`)"


def _tool_section(spec: ToolSpec, tool: Any) -> list[str]:
    lines = [f"### `{spec.name}`: {spec.title}", ""]
    meta = [_badges(spec), f"Profiles: {_profiles(spec.name)}", f"Windows-MCP: `{NAMES[spec.name]}`"]
    lines += [" · ".join(part for part in meta if part), ""]
    lines += [line.rstrip() for line in spec.description.splitlines()] + [""]
    lines += [*_parameters(tool.input_schema), ""]
    returns = _returns(tool.output_schema)
    if returns:
        lines += [returns, ""]
    return lines


def _profiles_table() -> list[str]:
    uses = {
        "minimal": "Small or local models",
        "standard": "The default: most users",
        "full": "Power users (scripting and browser tools included, still policy-gated)",
        "computer": "Vision-first computer-use loops",
    }
    order = [name for tools in TOOLSETS.values() for name in tools]
    rows = ["| Profile | Tools | Use |", "|---|---|---|"]
    for profile, tools in PROFILES.items():
        listed = ", ".join(f"`{name}`" for name in order if name in tools)
        rows.append(f"| `{profile}` | {listed} | {uses.get(profile, '')} |")
    return rows


def _windows_mcp(windows: dict[str, Any]) -> list[str]:
    lines = [
        "## The `windows-mcp` naming",
        "",
        '`[tools] naming = "windows-mcp"` (or `--naming windows-mcp`) exposes the tools under',
        "[Windows-MCP](https://github.com/CursorTouch/Windows-MCP)'s names and parameter shapes, so",
        "Windows-MCP prompts and agents carry over. `label` is a snapshot ref's number (`label=12` is",
        "`e12`), `loc` is `[x, y]` in screen points, and shortcuts use `cmd` where Windows uses `ctrl`.",
        "Each server exposes one naming.",
        "",
        "| Windows-MCP name | AXPilot tool | Parameters |",
        "|---|---|---|",
    ]
    publics = [*NAMES.items(), *((public, canonical) for public, canonical in EXTRA_NAMES.items())]
    rows: list[tuple[int, str]] = []
    order = list(NAMES)
    for item in publics:
        canonical, public = (item[0], item[1]) if item[0] in NAMES else (item[1], item[0])
        tool = windows.get(public)
        if tool is None:
            note = "only when `move_mouse` is disabled (`Move` drags)" if public == "Drag" else "not exposed"
            params = note
        else:
            names = list(tool.input_schema.get("properties", {}))
            params = ", ".join(f"`{name}`" for name in names) or "none"
        rows.append((order.index(canonical), f"| `{public}` | `{canonical}` | {params} |"))
    lines += [row for _, row in sorted(rows, key=lambda item: item[0])]
    lines += [
        "",
        "Windows-MCP's `FileSystem` has no counterpart: use a filesystem MCP server, `Spotlight` or",
        "`Shell`. `PowerShell` is `Shell` (zsh) and `Registry` is `Defaults` (macOS preferences).",
        "",
    ]
    return lines


def render() -> str:
    load_tool_modules()

    async def both() -> tuple[dict[str, Any], dict[str, Any]]:
        return await _listing("default"), await _listing("windows-mcp")

    default, windows = anyio.run(both)
    lines = [INTRO, "## Profiles", "", *_profiles_table(), ""]
    lines += [
        "Add or remove tools or whole toolsets with `[tools] enable` / `disable` (for example",
        '`enable = ["scripting"]`). `tools/list` returns tools in this page\'s order.',
        "",
    ]
    for toolset, names in TOOLSETS.items():
        lines += [f"## `{toolset}`", "", TOOLSET_NOTES[toolset], ""]
        for name in names:
            lines += _tool_section(REGISTRY[name], default[name])
    lines += _windows_mcp(windows)
    lines += [ERRORS]
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/tools.md is out of date")
    args = parser.parse_args(argv)
    text = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if args.check:
        if current != text:
            print(
                "docs/tools.md is out of date: run `uv run python scripts/gen_tool_docs.py`.", file=sys.stderr
            )
            return 1
        return 0
    if current != text:
        TARGET.write_text(text, encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
