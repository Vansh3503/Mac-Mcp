INTRO = """\
# Tools

<!-- Generated by scripts/gen_tool_docs.py from the tool registry. Do not edit by hand. -->

This is the reference of every AXPilot tool: what it does, its annotations, the profiles that
include it, its parameters and the fields of its result. Each tool's description below is exactly
what `tools/list` returns to MCP clients. `axpilot tools --json` prints the full input and output
schemas.

## Concepts

**Snapshots and refs.** `snapshot` lists an app's elements with short refs (`e1`, `e2`, …) inside
a snapshot (`s_7f3a`). Input tools take a `ref`. A ref keeps naming its element across snapshots
of the window while the element exists, and a ref number is never reused for another element;
when the element is gone or changed, the ref gives `STALE_REF` instead of hitting something else.
Pass a bare ref, or qualify it with its snapshot (`s_7f3a:e12`). OCR elements (`o1`, …) appear in
`vision` mode for apps with a poor accessibility tree.

```
app Notes (com.apple.Notes, pid 812) · window "Notes" [0,25 1440×875] · snapshot s_7f3a
focused: e39 textarea "Note body"
e13  button     "New Note"                    (484,52)
e26  list       "Notes"                       14 rows, scrollable
e27    row      "Shopping list — 10:42"       selected  (344,197)
menus: Notes · File · Edit · Format · View · Window · Help   (use select_menu)
```

Points are element centres in global screen **points** (origin at the top-left of the main
display; displays to the left or above have negative coordinates). Tools that take a point also
accept `coordinate_space: "screenshot"` with a `screenshot_id`, so a model can pass pixel
coordinates read off a (possibly downscaled) screenshot.

**Act, then observe.** Input tools take `report: "diff" | "snapshot" | "none"` (default `diff`):
after acting, AXPilot waits for the UI to settle and reports what changed (focus, added and
removed elements, new windows or dialogs, changed values) with the new `snapshot_id`.

**Strategies.** `strategy: "auto"` tries the most robust approach first and records what it tried:

| Intent | Strategy ladder |
|---|---|
| Click an element | Accessibility action (`AXPress`, works in the background) → raise the window and click its centre |
| Type text | Set the value / insert at the selection → keystrokes (layout-independent) → paste for long text (clipboard restored) |
| Shortcut | Layout-aware key codes plus modifiers |
| Scroll | Scroll the element into view (accessibility) → scroll-wheel events, measuring the app's line height |
| Menu command | Accessibility traversal of the menu bar with fuzzy path matching |
| Point click | Allowed, but hit-tested first: the app under the point must pass the safety policy |

Input actions are never retried automatically.

**Annotations and safety.** Every tool declares MCP annotations (`readOnlyHint`,
`destructiveHint`, `idempotentHint`, `openWorldHint`). *Input* tools take the single input lock,
count against the rate limit and yield to the user. Tools marked *asks first* show the user a
confirmation by default ([Configuration](configuration.md#safety)); the code-running ones show the
exact command or script.
"""

